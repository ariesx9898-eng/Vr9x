"""Casting clips of the ability overhaul (Docs/Ability_Overhaul.md §7) for both lineages, on the shared skeleton.

Every element spell has its own clip and silhouette instead of the three generic casts it used to borrow:

  Cast_Fireball (+ _Hold loop, _Release)   right palm up, the fingers cup and turn the sphere while the left hand shapes it
                                          from above; released as a push-toss off the palm
  Cast_FlameWave                          gather at the left hip, one long horizontal sweep of the right arm across the front
  Cast_Inferno        (full body)         right hand raised overhead, clenched, the fist driven down into a crouch
  Cast_WaterBullet                        index and middle finger aimed, snap forward, the fingers kick up (recoil)
  Cast_WaterDragon    (full body)         both hands twirl upward in mirrored rising circles, the body rising, then point
  Cast_Flood          (full body)         both arms gather back (weight back, front foot lifts), stomp and double push forward
  Cast_StoneCannon (+ _Hold, _Release)    right hand forward, fingers claw round the slug, palm thrust, small recoil
  Cast_EarthWall                          crouch, right palm under the earth, driven up above the head
  Cast_EarthSpikes                        right hand raised, driven down and forward along the aim line
  Cast_WindBlade                          knife hand from the left shoulder, one flat fast slash to the right
  Cast_Tornado                            index pointing down, stirring circles that rise, flung up
  Cast_WindBurst                          fists pulled in (compress), arms thrown open (release)

Rudeus's signature upgrades (StoneCannon_Charge / _Hold / _Release: raised hand, compression, braced forearm, palm thrust
and recoil; Quagmire / _Hold / _Release: left palm pressed at the ground; Barrage: 4.6 s of formations, point, paired
directing gestures, converge and push) and Orsted's DisturbMagic and DragonCrush are here too.

Casting hand (the effect's cast socket): the right hand (hand_r) for every element spell, Stone Cannon, Disturb Magic and
Dragon Crush; the left hand (hand_l) for Quagmire; both hands work in Barrage, Flood, Water Dragon and Wind Burst (the right
one points or leads).

Personality (§4). Rudeus's hands shape the magic: fingers curl, fan and roll, wrists turn, energy is gathered and each
release is directed, with recoil after the big ones. Orsted's versions are 55-65% as long, upright, one small gesture of
one hand (an overhead raise stays a raise, a sweep stays a sweep), no crouch except a slight knee bend on the heavy
techniques, and they start and end on his guard.

Timing (§7). Every one-shot starts and ends on the lineage's stance (Rudeus: clips.COMBAT, Orsted: clips_orsted.GUARD),
so montage blends never move a planted foot. The `Release` event is the frame the spell leaves the hand; an
anticipation clip of a chargeable spell ends exactly on its hold loop's first pose, the loop is seamless, and the release
clip starts on that same pose (its `Release` is 0.04 s). Lengths are whole 30 fps frames (F(n)).

How the keys were made: GENERATED by Tools/anim/cast_design/generate.py from hand-target designs (wrist position, palm
normal, finger direction per key, in each lineage's own proportions: cast_design/spells_rudeus.py, spells_orsted.py),
solved into the composer's arm parameters within anatomical ranges by an arm IK design aid (cast_design/armik.py), each key
starting from the previous one so interpolation stays on one branch; then checked on contact sheets and by
qa_animation_quality.py. To change a clip, edit its design (or this file's template, cast_design/clips_spells.template)
and re-run generate.py; hand edits here are overwritten.
New composer parameters used here (pose_compose.DEFAULTS, all 0 by default): <side>_roll (forearm roll, + = palm up),
<side>_fan (fingers spread), <side>_ci / _cm / _cr / _cp (extra curl of index / middle / ring / little finger).
"""
import math

TAU = 2.0 * math.pi
FPS = 30


def F(n):
    """n whole frames at 30 fps: exported lengths and event times line up with the importer's frames."""
    return n / FPS


def _m(*dicts):
    out = {}
    for d in dicts:
        out.update(d)
    return out


def _wave(w, phase):
    """A sine that is 0 at w = 0: hold loops start exactly on their hold pose (the anticipation's last frame)."""
    return math.sin(w + phase) - math.sin(phase)


