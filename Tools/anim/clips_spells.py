def fireball_hold(P0, period):
    """The fingers roll the sphere inward (a wave from the index to the little finger), the palm turns under it and the
    left hand circles over it."""
    def fn(t):
        w = TAU * (t % period) / period
        P = dict(P0)
        for i, k in enumerate(("R_ci", "R_cm", "R_cr", "R_cp")):
            P[k] = P0.get(k, 0.0) + 8.0 * _wave(w, -0.9 * i)
        for i, k in enumerate(("L_ci", "L_cm", "L_cr", "L_cp")):
            P[k] = P0.get(k, 0.0) + 5.0 * _wave(w, 0.9 * i + 1.0)
        P["R_roll"] = P0.get("R_roll", 0.0) + 5.0 * math.sin(w)
        P["R_wyaw"] = P0.get("R_wyaw", 0.0) + 3.0 * math.sin(2.0 * w)
