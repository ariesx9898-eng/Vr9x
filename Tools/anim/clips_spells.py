def still_hold(P0, period, side="R", fingers=3.0, wrist=2.0):
    """Orsted holding a spell: almost still, a slow finger wave and a slight turn of the wrist."""
    def fn(t):
        w = TAU * (t % period) / period
        P = dict(P0)
        for i, k in enumerate(("ci", "cm", "cr", "cp")):
            P[side + "_" + k] = P0.get(side + "_" + k, 0.0) + fingers * _wave(w, -0.8 * i)
        P[side + "_roll"] = P0.get(side + "_roll", 0.0) + wrist * math.sin(w)
        P["hair_lag"] = P0.get("hair_lag", 0.0) + 0.3 * math.sin(w)
        return P
    return fn


